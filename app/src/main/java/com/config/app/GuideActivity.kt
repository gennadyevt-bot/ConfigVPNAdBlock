package com.config.app

import android.os.Bundle
import android.widget.ImageView
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity

class GuideActivity : AppCompatActivity() {

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_guide)
        applyReleaseInsets()

        findViewById<ImageView>(R.id.ivBack).setOnClickListener { finish() }

        val tvGuide = findViewById<TextView>(R.id.tvGuide)
        tvGuide.text = buildGuideText()
    }

    private fun buildGuideText(): String {
        return """
📘 КАК ПОЛЬЗОВАТЬСЯ CONFIG VPN

━━━━━━━━━━━━━━━━━━━━━━━

🚀 1. ДОБАВИТЬ СЕРВЕР

   🔹 Нажми кнопку ➕ (плюс)
   🔹 Вставь конфиг вручную ИЛИ
   🔹 Нажми "QR" — отсканируй QR-код
   🔹 Нажми "Файлы" — выбери .conf файл
   🔹 Нажми "Сохранить"

   💡 Можно добавить до 6 серверов

━━━━━━━━━━━━━━━━━━━━━━━

⚡ 2. ПОДКЛЮЧИТЬ VPN

   🔹 Нажми "CONNECT" на нужном сервере
   🔹 Android спросит разрешение VPN
   🔹 Нажми "Разрешить" (один раз)
   🔹 Статус станет 🟢 CONNECTED

   💡 Повторное подключение не спрашивает

━━━━━━━━━━━━━━━━━━━━━━━

🛑 3. ОТКЛЮЧИТЬ VPN

   🔹 Нажми "STOP" на активном сервере
   🔹 ИЛИ свайп уведомление вниз → "Отключить"

━━━━━━━━━━━━━━━━━━━━━━━

🤖 4. APP VPN — АВТО ВКЛЮЧЕНИЕ

   🔹 Меню (☰) → App VPN
   🔹 Выбери приложения (Telegram, Chrome...)
   🔹 Нажми "Сохранить"
   🔹 Открой выбранное приложение →
      VPN включится автоматически!

   💡 При выходе из приложения VPN отключится

━━━━━━━━━━━━━━━━━━━━━━━

🌐 5. DOMAIN VPN (экспериментально)

   🔹 Меню (☰) → Domain VPN
   🔹 Добавь домены (rutracker.org...)
   🔹 Включи Accessibility Service
   🔹 При переходе по ссылкам VPN включится

   ⚠️ Работает не на всех телефонах

━━━━━━━━━━━━━━━━━━━━━━━

💾 6. БЭКАП

   🔹 Меню (☰) → Backup
   🔹 Нажми "Share" — отправь JSON файл
   🔹 На новом телефоне: Файлы → выбери JSON

━━━━━━━━━━━━━━━━━━━━━━━

🔁 7. АВТО-ПОДКЛЮЧЕНИЕ

   🔹 Меню (☰) → Auto Connect
   🔹 Включи тумблер
   🔹 При запуске приложения VPN
     подключится к первому рабочему серверу

━━━━━━━━━━━━━━━━━━━━━━━

📱 8. РАЗРЕШЕНИЯ ТЕЛЕФОНА (ОБЯЗАТЕЛЬНО!)

   Чтобы VPN не отключался:

   🔋 БАТАРЕЯ:
      Настройки → Приложения → Config
      → Использование батареи →
      "Не ограничивать" / "Неограниченно"

   🚀 АВТОЗАПУСК:
      Настройки → Приложения → Config
      → Автозапуск → ВКЛ

   ⏸️ НЕ ПРИОСТАНАВЛИВАТЬ:
      Настройки → Приложения → Config
      → "Приостанавливать действия
         неиспользуемых приложений" → ВЫКЛ

   📊 СТАТИСТИКА ТРАФИКА:
      Настройки → Приложения → Config
      → Статистика трафика → ВКЛ
      (нужно для App VPN)

   🔒 ACCESSIBILITY:
      Настройки → Спец. возможности →
      Config VPN Domain Service → ВКЛ
      (нужно для Domain VPN)

   🔔 УВЕДОМЛЕНИЯ:
      Настройки → Приложения → Config
      → Уведомления → ВКЛ

━━━━━━━━━━━━━━━━━━━━━━━

🔄 9. ПОСЛЕ ПЕРЕЗАГРУЗКИ

   Если всё настроено правильно:
   🔹 При включении телефона сервис
      запустится автоматически
   🔹 Открой Telegram/Chrome →
      VPN включится сам

   Если не работает — проверь
   разрешения (пункт 8)

━━━━━━━━━━━━━━━━━━━━━━━

❓ ПРОБЛЕМЫ?

   🔴 "Ошибка подключения"
      → Проверь ключи и endpoint

   🔴 VPN отключается сам
      → Проверь разрешения батареи

   🔴 App VPN не работает
      → Дай разрешение "Статистика трафика"

   🔴 Не импортирует файл
      → Файл должен быть .conf или .txt

━━━━━━━━━━━━━━━━━━━━━━━

📦 Версия: 4.6.0 | WireGuard + AmneziaWG
        """.trimIndent()
    }
}
